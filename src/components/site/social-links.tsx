export function SocialGlyph({ network, className }: { network: string; className?: string }) {
  const g = glyphs[network];
  if (!g) return null;
  return (
    <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden className={cn("size-4", className)}>
      {g}
    </svg>
  );
}

export function SocialLinks({
  socials,
  email,
  className,
}: {
  socials: Record<string, string>;
  email?: string;
  className?: string;
}) {
  const entries = Object.entries(socials).filter(([, url]) => /^https?:\/\//.test(url));
  if (!entries.length && !email) return null;
  return (
    <ul className={cn("flex flex-wrap items-center gap-1.5", className)}>
      {entries.map(([network, url]) => (
        <li key={network}>
          <a
            href={url}
            target="_blank"
            rel="me noopener"
            aria-label={socialLabels[network] ?? network}
            className="inline-flex size-9 items-center justify-center rounded-full border border-border text-muted-foreground transition-colors hover:border-foreground/30 hover:text-foreground"
          >
            <SocialGlyph network={network} />
          </a>
        </li>
      ))}
      {email && (
        <li>
          <a
            href={`mailto:${email}`}
            aria-label={email}
            className="inline-flex size-9 items-center justify-center rounded-full border border-border text-muted-foreground transition-colors hover:border-foreground/30 hover:text-foreground"
          >
            <MailIcon className="size-4" />
          </a>
        </li>
      )}
    </ul>
  );
}
